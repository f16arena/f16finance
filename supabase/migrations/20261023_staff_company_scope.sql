-- Охват сотрудника по точкам: «управляющий двух точек из пяти».
--
-- Раньше любой сотрудник организации видел все её точки (resolveCompanyScope отдавал
-- организацию целиком). Теперь у сотрудника может быть список точек: он видит только
-- их — доходы, расходы, склад, смены, операторов этих точек. NULL — все точки, как
-- было. Владельцу охват не задаётся. Задаёт владелец на странице сотрудников.

alter table public.staff
  add column if not exists company_ids uuid[];

comment on column public.staff.company_ids is
  'Точки, которые видит сотрудник. NULL — все точки организации (как было до охвата).';
